/**
 * Generate companion CSS for One Dark (matches @codemirror/theme-one-dark tokens).
 */
function generateOneDarkCss() {
  const c = {
    chalky: '#e5c07b',
    coral: '#e06c75',
    cyan: '#56b6c2',
    invalid: '#ffffff',
    ivory: '#abb2bf',
    stone: '#7d8799',
    malibu: '#61afef',
    sage: '#98c379',
    whiskey: '#d19a66',
    violet: '#c678dd',
    darkBackground: '#21252b',
    highlightBackground: '#2c313a',
    background: '#282c34',
    tooltipBackground: '#353a42',
    selection: '#3E4451',
    cursor: '#528bff',
  };

  const root = '.cm-editor.cm-theme-one-dark';

  return `/* CodeMirror 6 — One Dark companion stylesheet
 * Use with createEditor when theme is oneDark; pairs with cm-theme-one-dark on .cm-editor
 * Generated by codemirror_generator — https://codemirror.net/
 */

${root} {
  color: ${c.ivory};
  background-color: ${c.background};
}

${root} .cm-content {
  caret-color: ${c.cursor};
}

${root} .cm-cursor,
${root} .cm-dropCursor {
  border-left-color: ${c.cursor};
}

${root}.cm-focused > .cm-scroller > .cm-selectionLayer .cm-selectionBackground,
${root} .cm-selectionBackground,
${root} .cm-content ::selection {
  background-color: ${c.selection};
}

${root} .cm-panels {
  background-color: ${c.darkBackground};
  color: ${c.ivory};
}

${root} .cm-activeLine {
  background-color: #6699ff0b;
}

${root} .cm-selectionMatch {
  background-color: #aafe661a;
}

${root}.cm-focused .cm-matchingBracket,
${root}.cm-focused .cm-nonmatchingBracket {
  background-color: #bad0f847;
}

${root} .cm-gutters {
  background-color: ${c.background};
  color: ${c.stone};
  border: none;
}

${root} .cm-activeLineGutter {
  background-color: ${c.highlightBackground};
}

${root} .cm-tooltip {
  border: none;
  background-color: ${c.tooltipBackground};
}

/* Syntax tokens (classHighlightStyle / Lezer tags) */
${root} .cmt-keyword { color: ${c.violet}; }
${root} .cmt-name,
${root} .cmt-deleted,
${root} .cmt-character,
${root} .cmt-propertyName,
${root} .cmt-macroName { color: ${c.coral}; }
${root} .cmt-function,
${root} .cmt-labelName { color: ${c.malibu}; }
${root} .cmt-color,
${root} .cmt-constant,
${root} .cmt-standard { color: ${c.whiskey}; }
${root} .cmt-definition,
${root} .cmt-separator { color: ${c.ivory}; }
${root} .cmt-typeName,
${root} .cmt-className,
${root} .cmt-number,
${root} .cmt-changed,
${root} .cmt-annotation,
${root} .cmt-modifier,
${root} .cmt-self,
${root} .cmt-namespace { color: ${c.chalky}; }
${root} .cmt-operator,
${root} .cmt-operatorKeyword,
${root} .cmt-url,
${root} .cmt-escape,
${root} .cmt-regexp,
${root} .cmt-link { color: ${c.cyan}; }
${root} .cmt-meta,
${root} .cmt-comment { color: ${c.stone}; }
${root} .cmt-strong { font-weight: bold; }
${root} .cmt-emphasis { font-style: italic; }
${root} .cmt-strikethrough { text-decoration: line-through; }
${root} .cmt-heading { font-weight: bold; color: ${c.coral}; }
${root} .cmt-atom,
${root} .cmt-bool { color: ${c.whiskey}; }
${root} .cmt-processingInstruction,
${root} .cmt-string,
${root} .cmt-inserted { color: ${c.sage}; }
${root} .cmt-invalid { color: ${c.invalid}; }
`;
}

/**
 * @param {string} themeId
 * @returns {string|null}
 */
function generateThemeCss(themeId) {
  if (themeId === 'oneDark') return generateOneDarkCss();
  return null;
}

module.exports = { generateThemeCss, generateOneDarkCss };
